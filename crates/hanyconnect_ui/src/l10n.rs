#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum UiLocale {
    #[default]
    ZhCn,
    En,
}

impl UiLocale {
    pub fn from_tag(tag: &str) -> Self {
        let lower = tag.to_ascii_lowercase();
        if lower.starts_with("zh") {
            Self::ZhCn
        } else {
            Self::En
        }
    }
}

pub fn tr(locale: UiLocale, zh: &'static str, en: &'static str) -> &'static str {
    match locale {
        UiLocale::ZhCn => zh,
        UiLocale::En => en,
    }
}

