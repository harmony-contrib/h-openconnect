#!/usr/bin/env sh
set -eu
ROOT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
. "$ROOT_DIR/scripts/ohos-env.sh"

NSH_PROFILE=${NSH_PROFILE:-${NATIVE_PROFILE:-release}}
case "$NSH_PROFILE" in
  debug|release) ;;
  *) echo 'NSH_PROFILE must be debug or release' >&2; exit 2 ;;
esac

NSH_OUTPUT="${NSH_SDK_OUTPUT:-$ROOT_DIR/dist/nsh-sdk/$NSH_PROFILE}"
NSH_TARGET="${NSH_TARGET_DIR:-$ROOT_DIR/target/nsh}"
case "$NSH_TARGET" in /*) ;; *) NSH_TARGET="$ROOT_DIR/$NSH_TARGET" ;; esac
export CARGO_TARGET_DIR="$NSH_TARGET"
export CARGO_INCREMENTAL="${CARGO_INCREMENTAL:-0}"

mkdir -p "$NSH_OUTPUT"
NSH_INPUTS=$(mktemp "$NSH_OUTPUT/source-inputs.XXXXXX")
trap 'rm -f "$NSH_INPUTS"' EXIT HUP INT TERM
python3 "$ROOT_DIR/scripts/nsh_build_inputs.py" > "$NSH_INPUTS"

HARMONYOS_SRC_DIR=$(python3 "$ROOT_DIR/scripts/nsh_build_inputs.py" --field harmonyosRoot)
NSH_CORE_VERSION=$(python3 "$ROOT_DIR/scripts/nsh_build_inputs.py" --field nshCoreVersion)
NSH_MINOR_PREFIX=$(printf '%s' "$NSH_CORE_VERSION" | awk -F. '{print $1 "." $2 "."}')

NSH_CLI_SOURCE=explicit-override
if [ -z "${NSH_BIN:-}" ]; then
  if command -v nsh >/dev/null 2>&1; then
    INSTALLED_NSH=$(command -v nsh)
    INSTALLED_VER=$("$INSTALLED_NSH" --version 2>/dev/null || true)
    case "$INSTALLED_VER" in
      "nsh $NSH_MINOR_PREFIX"*)
        NSH_BIN="$INSTALLED_NSH"
        NSH_CLI_SOURCE=system-path
        ;;
    esac
  fi
fi

if [ -z "${NSH_BIN:-}" ]; then
  CACHED_NSH="$NSH_TARGET/cli/bin/nsh"
  if [ -x "$CACHED_NSH" ]; then
    CACHED_VER=$("$CACHED_NSH" --version 2>/dev/null || true)
    case "$CACHED_VER" in
      "nsh $NSH_MINOR_PREFIX"*)
        NSH_BIN="$CACHED_NSH"
        NSH_CLI_SOURCE=cargo-install-cache
        ;;
    esac
  fi
fi

if [ -z "${NSH_BIN:-}" ]; then
  cargo install nsh-cli --version "=$NSH_CORE_VERSION" --locked --root "$NSH_TARGET/cli"
  NSH_BIN="$NSH_TARGET/cli/bin/nsh"
  NSH_CLI_SOURCE=crates-io-install
fi

test -x "$NSH_BIN" || { echo "NSH CLI is not executable: $NSH_BIN" >&2; exit 1; }

if [ "${NSH_REUSE_SDK:-0}" = 1 ]; then
  python3 - "$ROOT_DIR/scripts" "$NSH_OUTPUT/source-inputs.json" "$NSH_INPUTS" "$NSH_BIN" <<'PY_REUSE'
import hashlib, json, sys
from pathlib import Path
sys.path.insert(0, sys.argv[1])
from nsh_build_inputs import verify_source_identity
recorded, current = [json.loads(Path(path).read_text()) for path in sys.argv[2:4]]
try:
    verify_source_identity(recorded, current)
except ValueError as error:
    raise SystemExit(str(error)) from None
with Path(sys.argv[4]).open('rb') as stream:
    digest = hashlib.file_digest(stream, 'sha256').hexdigest()
if digest != recorded.get('cli', {}).get('sha256'):
    raise SystemExit('The NSH CLI differs from the build record; rebuild before reuse')
PY_REUSE
else
  if [ -n "${NSH_HARMONYOS_ROOT:-}" ]; then
    NSH_RUNNER="$NSH_TARGET/harmonyos-runner-local"
    python3 - "$NSH_HARMONYOS_ROOT" "$NSH_RUNNER" <<'PY_LOCAL_RUNNER'
import shutil, sys
from pathlib import Path

harmonyos = Path(sys.argv[1]).resolve(strict=True)
runner = Path(sys.argv[2])
runner.mkdir(parents=True, exist_ok=True)
manifest = f'''# Generated by H-OpenConnect scripts/build-nsh-ohos.sh for local override.
[package]
name = "nsh-harmonyos-runner"
version = "0.0.0"
edition = "2024"
publish = false

[lib]
name = "nsh_platform_harmonyos"
path = "lib.rs"
crate-type = ["cdylib"]

[dependencies]
backend = {{ package = "nsh-platform-harmonyos", path = {str(harmonyos)!r} }}

[build-dependencies]
napi-build-ohos = "1.2"

[profile.release]
lto = "fat"
codegen-units = 1
strip = true

[profile.dev.package.quickjs-jit-sys]
opt-level = 3
[profile.dev.package.taffy]
opt-level = 3

[workspace]
'''
(runner / 'Cargo.toml').write_text(manifest)
(runner / 'lib.rs').write_text('backend::app!();\n')
(runner / 'build.rs').write_text('fn main() {\n    napi_build_ohos::setup();\n}\n')
if (harmonyos / 'Cargo.lock').is_file():
    shutil.copyfile(harmonyos / 'Cargo.lock', runner / 'Cargo.lock')
PY_LOCAL_RUNNER
    RUNNER_DIR="$NSH_RUNNER"
    CARGO_LOCK_ARGS=""
  else
    RUNNER_DIR="$ROOT_DIR/scripts/nsh-harmonyos-runner"
    CARGO_LOCK_ARGS="--locked"
  fi

  cd "$RUNNER_DIR"
  rm -f "$NSH_OUTPUT/arm64-v8a/libnsh_platform_harmonyos.so" "$NSH_OUTPUT/index.d.ts"
  if [ "$NSH_PROFILE" = release ]; then
    # shellcheck disable=SC2086
    "${OHRS:-ohrs}" build -a aarch --release --dist "$NSH_OUTPUT" --target-dir "$NSH_TARGET" -- $CARGO_LOCK_ARGS
  else
    # shellcheck disable=SC2086
    "${OHRS:-ohrs}" build -a aarch --dist "$NSH_OUTPUT" --target-dir "$NSH_TARGET" -- $CARGO_LOCK_ARGS
  fi

  if [ -f "$HARMONYOS_SRC_DIR/arkts/src/main/cpp/types/libnsh_platform_harmonyos/Index.d.ts" ]; then
    cp "$HARMONYOS_SRC_DIR/arkts/src/main/cpp/types/libnsh_platform_harmonyos/Index.d.ts" "$NSH_OUTPUT/index.d.ts"
  elif [ -f "$HARMONYOS_SRC_DIR/crates/nsh-platform-harmonyos/arkts/src/main/cpp/types/libnsh_platform_harmonyos/Index.d.ts" ]; then
    cp "$HARMONYOS_SRC_DIR/crates/nsh-platform-harmonyos/arkts/src/main/cpp/types/libnsh_platform_harmonyos/Index.d.ts" "$NSH_OUTPUT/index.d.ts"
  fi
fi

test -s "$NSH_OUTPUT/arm64-v8a/libnsh_platform_harmonyos.so" || { echo 'NSH native build produced no library' >&2; exit 1; }
test -s "$NSH_OUTPUT/index.d.ts" || { echo 'NSH native build produced no declarations' >&2; exit 1; }

if [ "$NSH_BIN" != "$NSH_OUTPUT/nsh" ]; then
  cp "$NSH_BIN" "$NSH_OUTPUT/nsh.tmp"
  mv -f "$NSH_OUTPUT/nsh.tmp" "$NSH_OUTPUT/nsh"
fi

python3 - "$ROOT_DIR/scripts" "$NSH_INPUTS" "$NSH_OUTPUT/source-inputs.json" "$NSH_BIN" "$NSH_CLI_SOURCE" <<'PY_ATTEST'
import hashlib, json, subprocess, sys
from pathlib import Path
sys.path.insert(0, sys.argv[1])
from nsh_build_inputs import resolve_inputs, verify_source_identity
inputs = json.loads(Path(sys.argv[2]).read_text())
verify_source_identity(inputs, resolve_inputs())
cli = Path(sys.argv[4]).resolve(strict=True)
version = subprocess.check_output([str(cli), '--version'], text=True, timeout=15).strip()
digest = hashlib.sha256()
with cli.open('rb') as stream:
    for chunk in iter(lambda: stream.read(1 << 20), b''):
        digest.update(chunk)
inputs['cli'] = {
    'path': str(cli),
    'version': version,
    'sha256': digest.hexdigest(),
    'sourceKind': sys.argv[5],
}
Path(sys.argv[3]).write_text(json.dumps(inputs, indent=2) + '\n')
PY_ATTEST

cd "$ROOT_DIR"
mkdir -p target/ohos/hopenconnect-bundle entry/src/main/resources/rawfile entry/src/main/cpp/types/libnsh_platform_harmonyos entry/libs/arm64-v8a
if [ "$NSH_PROFILE" = release ]; then
  "$NSH_BIN" build --release "$ROOT_DIR/ui/nsh" -o "$ROOT_DIR/target/ohos/hopenconnect-bundle"
else
  "$NSH_BIN" build "$ROOT_DIR/ui/nsh" -o "$ROOT_DIR/target/ohos/hopenconnect-bundle"
fi
test -s "$ROOT_DIR/target/ohos/hopenconnect-bundle/bundle.nshc" || {
  echo 'NSH build produced no bytecode bundle (bundle.nshc)' >&2
  exit 1
}
cp "$ROOT_DIR/target/ohos/hopenconnect-bundle/bundle.nshc" "$ROOT_DIR/entry/src/main/resources/rawfile/hopenconnect.bundle.nshc"
rm -f "$ROOT_DIR/entry/src/main/resources/rawfile/hopenconnect.bundle.js"
for companion in app.json capabilities.json; do
  if [ -f "$ROOT_DIR/target/ohos/hopenconnect-bundle/$companion" ]; then
    cp "$ROOT_DIR/target/ohos/hopenconnect-bundle/$companion" "$ROOT_DIR/entry/src/main/resources/rawfile/$companion"
  else
    rm -f "$ROOT_DIR/entry/src/main/resources/rawfile/$companion"
  fi
done
if [ -d "$ROOT_DIR/target/ohos/hopenconnect-bundle/assets" ]; then
  mkdir -p "$ROOT_DIR/entry/src/main/resources/rawfile/assets"
  cp -R "$ROOT_DIR/target/ohos/hopenconnect-bundle/assets/." "$ROOT_DIR/entry/src/main/resources/rawfile/assets/"
fi
cp "$NSH_OUTPUT/arm64-v8a/libnsh_platform_harmonyos.so" "$ROOT_DIR/entry/libs/arm64-v8a/libnsh_platform_harmonyos.so"
cp "$NSH_OUTPUT/index.d.ts" "$ROOT_DIR/entry/src/main/cpp/types/libnsh_platform_harmonyos/Index.d.ts"
cp "$NSH_OUTPUT/source-inputs.json" "$ROOT_DIR/target/ohos/nsh-source-inputs.json"
python3 "$ROOT_DIR/scripts/prepare-nsh-arkts.py"
ohpm install --all
